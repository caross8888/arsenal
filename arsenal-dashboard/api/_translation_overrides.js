//  - 이번 한 번뿐이다(기자의 조어, 비꼬는 말투, 문맥 없는 짧은 문장) → 여기
// 규칙은 늘어날수록 엉뚱한 문장에 걸릴 위험이 커지지만(실제로 "촬영 → 슈팅"이
// 유튜브 제목의 "사진 촬영"까지 바꿨다), 여기 등록한 건 원문이 정확히 같은 항목
// 하나에만 적용돼서 다른 문장에 영향이 없다. 구글 API도 부르지 않는다.
//
// 형식: { en: 원문, ko: 번역 }
//  - en: 영어 원문 전체(뉴스 제목/요약 한 필드, 유튜브 제목, SNS 포스트 본문 전체).
//        공백·줄바꿈 차이는 무시하고 비교하므로 줄바꿈은 신경 쓰지 않아도 된다.
//  - ko: 화면에 그대로 나갈 번역문. 번역 사전(_glossary.js)은 적용되지 않는다.
//  - SNS 포스트는 본문 속 링크(@핸들, 잘린 URL, #해시태그)를 ko 안에 원문 표기
//    그대로 적어야 한다 — 그 위치를 찾아서 클릭 가능한 링크로 되살린다. 하나라도
//    못 찾으면 이 교정은 무시되고 평소처럼 번역된다.
//
